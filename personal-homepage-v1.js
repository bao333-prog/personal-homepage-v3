function drawWarpFrame(stars, progress, direction) {
  const width = warpCanvas.clientWidth;
  const height = warpCanvas.clientHeight;
  const centerX = width * (direction > 0 ? .48 : .52);
  const centerY = height * .5;
  const reach = Math.hypot(width, height) * .62;
  const intensity = Math.sin(Math.PI * progress);
  warpContext.clearRect(0, 0, width, height);
  warpContext.fillStyle = `rgba(2, 4, 10, ${.24 + intensity * .2})`;
  warpContext.fillRect(0, 0, width, height);

  stars.forEach((star) => {
    const distance = ((star.seed * .18) + progress * progress * star.speed) % 1.12 * reach;
    const tail = 2 + intensity * star.length * .55;
    const cosine = Math.cos(star.angle);
    const sine = Math.sin(star.angle);
    const x = centerX + cosine * distance;
    const y = centerY + sine * distance;
    const gradient = warpContext.createLinearGradient(x - cosine * tail, y - sine * tail, x, y);
    gradient.addColorStop(0, 'rgba(112, 215, 223, 0)');
    gradient.addColorStop(.72, `rgba(112, 215, 223, ${.1 + intensity * .24})`);
    gradient.addColorStop(1, star.warm ? `rgba(255, 196, 107, ${.27 + intensity * .27})` : `rgba(246, 248, 243, ${.3 + intensity * .27})`);
    warpContext.beginPath();
    warpContext.moveTo(x - cosine * tail, y - sine * tail);
    warpContext.lineTo(x, y);
    warpContext.strokeStyle = gradient;
    warpContext.lineWidth = star.width + intensity * .45;
    warpContext.stroke();
  });
}

function runWarp(direction, swapPages) {
  if (reducedMotion.matches || paused) {
    swapPages();
    return Promise.resolve();
  }

  const bounds = warpTransition.getBoundingClientRect();
  const ratio = Math.min(window.devicePixelRatio || 1, 2);
  warpCanvas.width = Math.max(1, Math.round(bounds.width * ratio));
  warpCanvas.height = Math.max(1, Math.round(bounds.height * ratio));
  warpContext.setTransform(ratio, 0, 0, ratio, 0, 0);
  const duration = 780;
  const starCount = window.innerWidth < 700 ? 34 : 54;
  const stars = Array.from({ length: starCount }, (_, index) => ({
    angle: Math.random() * Math.PI * 2,
    seed: Math.random(),
    speed: random(.62, 1.08),
    length: random(22, 72),
    width: random(.3, .75),
    warm: index % 19 === 0
  }));

  warpTransition.classList.remove('is-active', 'is-reverse');
  void warpTransition.offsetWidth;
  warpTransition.classList.toggle('is-reverse', direction < 0);
  warpTransition.classList.add('is-active');

  return new Promise((resolve) => {
    const start = performance.now();
    let swapped = false;
    const render = (now) => {
      const progress = Math.min(1, (now - start) / duration);
      drawWarpFrame(stars, progress, direction);
      if (!swapped && progress >= .46) {
        swapped = true;
        swapPages();
      }
      if (progress < 1) {
        requestAnimationFrame(render);
        return;
      }
      if (!swapped) swapPages();
      warpTransition.classList.remove('is-active', 'is-reverse');
      warpContext.clearRect(0, 0, warpCanvas.clientWidth, warpCanvas.clientHeight);
      resolve();
    };
    requestAnimationFrame(render);
  });
}

