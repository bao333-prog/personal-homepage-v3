async function navigateToPage(pageId, options = {}) {
  const nextIndex = pageOrder.indexOf(pageId);
  if (nextIndex < 0 || nextIndex === currentPageIndex || pageTransitioning) return;
  pageTransitioning = true;
  const direction = nextIndex > currentPageIndex ? 1 : -1;
  const swapPages = () => showPage(nextIndex);

  if (options.skipAnimation) {
    swapPages();
  } else {
    await runWarp(direction, swapPages);
  }

  if (options.history !== false) history.pushState({ page: pageId }, '', `#${pageId}`);
  pageTransitioning = false;
}

