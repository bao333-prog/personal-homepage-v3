function random(min, max) {
  return Math.random() * (max - min) + min;
}

function makeStar() {
  return {
    x: Math.random(), y: Math.random(), radius: random(.25, 1.35),
    alpha: random(.2, .95), phase: random(0, Math.PI * 2),
    speed: random(.00035, .0012), depth: random(.15, 1)
  };
}

function makeDust() {
  return { x: Math.random(), y: Math.random(), radius: random(1, 3.2), alpha: random(.02, .09), depth: random(.1, .55) };
}

function resizeParticles(collection, count, factory) {
  collection.length = Math.min(collection.length, count);
  while (collection.length < count) collection.push(factory());
}

function resizeCanvas() {
  const bounds = universe.getBoundingClientRect();
  const nextWidth = Math.max(1, bounds.width);
  const nextHeight = Math.max(1, bounds.height);
  const nextPixelRatio = Math.min(window.devicePixelRatio || 1, 2);
  if (nextWidth === width && nextHeight === height && nextPixelRatio === pixelRatio) return;

  // A resize can fire repeatedly while the browser is settling its viewport.
  // Cancel the pending frame before drawing the resized canvas so loops cannot stack.
  cancelAnimationFrame(animationId);
  animationId = 0;
  width = nextWidth;
  height = nextHeight;
  pixelRatio = nextPixelRatio;
  canvas.width = Math.round(width * pixelRatio);
  canvas.height = Math.round(height * pixelRatio);
  context.setTransform(pixelRatio, 0, 0, pixelRatio, 0, 0);
  const count = Math.min(siteConfig.scene.maxStars, Math.floor(width * height / siteConfig.scene.starDensity));
  resizeParticles(stars, count, makeStar);
  resizeParticles(dust, siteConfig.scene.dustCount, makeDust);
  drawSpace(performance.now());
}

function spawnShootingStar() {
  if (shootingStars.length || Math.random() > .009) return;
  shootingStars.push({ x: random(width * .25, width * .9), y: random(0, height * .32), length: random(70, 150), life: 1, speed: random(8, 13) });
}

function drawSpace(time) {
  context.clearRect(0, 0, width, height);
  pointerX += (targetX - pointerX) * .035;
  pointerY += (targetY - pointerY) * .035;

  dust.forEach((particle) => {
    const x = particle.x * width + pointerX * particle.depth * 14;
    const y = particle.y * height + pointerY * particle.depth * 10;
    context.beginPath();
    context.fillStyle = `rgba(112, 215, 223, ${particle.alpha})`;
    context.arc(x, y, particle.radius, 0, Math.PI * 2);
    context.fill();
  });

  stars.forEach((star) => {
    const shimmer = paused ? .7 : .65 + Math.sin(time * star.speed + star.phase) * .35;
    const x = star.x * width + pointerX * star.depth * 22;
    const y = star.y * height + pointerY * star.depth * 15;
    context.beginPath();
    context.fillStyle = `rgba(235, 244, 244, ${star.alpha * shimmer})`;
    context.arc(x, y, star.radius, 0, Math.PI * 2);
    context.fill();
  });

  if (Math.abs(targetX) + Math.abs(targetY) > .05) {
    const glowX = (targetX + .5) * width;
    const glowY = (targetY + .5) * height;
    const glow = context.createRadialGradient(glowX, glowY, 0, glowX, glowY, 95);
    glow.addColorStop(0, 'rgba(112,215,223,.12)');
    glow.addColorStop(1, 'rgba(112,215,223,0)');
    context.fillStyle = glow;
    context.fillRect(glowX - 95, glowY - 95, 190, 190);
  }

  if (!paused) spawnShootingStar();
  shootingStars = shootingStars.filter((star) => star.life > 0);
  shootingStars.forEach((star) => {
    const gradient = context.createLinearGradient(star.x, star.y, star.x + star.length, star.y - star.length * .42);
    gradient.addColorStop(0, `rgba(255,255,255,${star.life})`);
    gradient.addColorStop(1, 'rgba(112,215,223,0)');
    context.beginPath();
    context.strokeStyle = gradient;
    context.lineWidth = 1;
    context.moveTo(star.x, star.y);
    context.lineTo(star.x + star.length, star.y - star.length * .42);
    context.stroke();
    star.x -= star.speed;
    star.y += star.speed * .42;
    star.life -= .018;
  });

  if (!paused) {
    animationId = requestAnimationFrame(drawSpace);
  } else {
    animationId = 0;
  }
}

